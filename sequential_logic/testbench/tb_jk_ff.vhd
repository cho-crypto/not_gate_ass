library ieee;
use ieee.std_logic_1164.all;

use std.env.all;

entity tb_jk_ff is end;
architecture test of tb_jk_ff is
  signal j, k, clk : std_logic := '0';
  signal q, qb, gq, gqb : std_logic;
begin
  dut: entity work.jk_ff(rtl) port map(j, k, clk, q, qb);
  net: entity work.jk_ff_gates(gates) port map(j, k, clk, gq, gqb);
  process
  begin
    j <= '0'; k <= '1'; clk <= '0';
    wait for 30 ns;
    report "PASS step 1: Prepare Reset" severity note;
    j <= '0'; k <= '1'; clk <= '1';
    wait for 30 ns;
    assert q = '0' and qb = '1' report "RTL step 2: Reset" severity failure;
    assert gq = '0' and gqb = '1' report "Gates step 2: Reset" severity failure;
    assert q = gq and qb = gqb report "Equivalence step 2" severity failure;
    report "PASS step 2: Reset" severity note;
    j <= '0'; k <= '0'; clk <= '1';
    wait for 30 ns;
    assert q = '0' and qb = '1' report "RTL step 3: High holds" severity failure;
    assert gq = '0' and gqb = '1' report "Gates step 3: High holds" severity failure;
    assert q = gq and qb = gqb report "Equivalence step 3" severity failure;
    report "PASS step 3: High holds" severity note;
    j <= '0'; k <= '0'; clk <= '0';
    wait for 30 ns;
    assert q = '0' and qb = '1' report "RTL step 4: Prepare Hold" severity failure;
    assert gq = '0' and gqb = '1' report "Gates step 4: Prepare Hold" severity failure;
    assert q = gq and qb = gqb report "Equivalence step 4" severity failure;
    report "PASS step 4: Prepare Hold" severity note;
    j <= '0'; k <= '0'; clk <= '1';
    wait for 30 ns;
    assert q = '0' and qb = '1' report "RTL step 5: Hold 0" severity failure;
    assert gq = '0' and gqb = '1' report "Gates step 5: Hold 0" severity failure;
    assert q = gq and qb = gqb report "Equivalence step 5" severity failure;
    report "PASS step 5: Hold 0" severity note;
    j <= '1'; k <= '0'; clk <= '0';
    wait for 30 ns;
    assert q = '0' and qb = '1' report "RTL step 6: Prepare Set" severity failure;
    assert gq = '0' and gqb = '1' report "Gates step 6: Prepare Set" severity failure;
    assert q = gq and qb = gqb report "Equivalence step 6" severity failure;
    report "PASS step 6: Prepare Set" severity note;
    j <= '1'; k <= '0'; clk <= '1';
    wait for 30 ns;
    assert q = '1' and qb = '0' report "RTL step 7: Set" severity failure;
    assert gq = '1' and gqb = '0' report "Gates step 7: Set" severity failure;
    assert q = gq and qb = gqb report "Equivalence step 7" severity failure;
    report "PASS step 7: Set" severity note;
    j <= '0'; k <= '0'; clk <= '0';
    wait for 30 ns;
    assert q = '1' and qb = '0' report "RTL step 8: Prepare Hold 1" severity failure;
    assert gq = '1' and gqb = '0' report "Gates step 8: Prepare Hold 1" severity failure;
    assert q = gq and qb = gqb report "Equivalence step 8" severity failure;
    report "PASS step 8: Prepare Hold 1" severity note;
    j <= '0'; k <= '0'; clk <= '1';
    wait for 30 ns;
    assert q = '1' and qb = '0' report "RTL step 9: Hold 1" severity failure;
    assert gq = '1' and gqb = '0' report "Gates step 9: Hold 1" severity failure;
    assert q = gq and qb = gqb report "Equivalence step 9" severity failure;
    report "PASS step 9: Hold 1" severity note;
    j <= '1'; k <= '1'; clk <= '0';
    wait for 30 ns;
    assert q = '1' and qb = '0' report "RTL step 10: Prepare Toggle" severity failure;
    assert gq = '1' and gqb = '0' report "Gates step 10: Prepare Toggle" severity failure;
    assert q = gq and qb = gqb report "Equivalence step 10" severity failure;
    report "PASS step 10: Prepare Toggle" severity note;
    j <= '1'; k <= '1'; clk <= '1';
    wait for 30 ns;
    assert q = '0' and qb = '1' report "RTL step 11: Toggle to 0" severity failure;
    assert gq = '0' and gqb = '1' report "Gates step 11: Toggle to 0" severity failure;
    assert q = gq and qb = gqb report "Equivalence step 11" severity failure;
    report "PASS step 11: Toggle to 0" severity note;
    j <= '1'; k <= '1'; clk <= '0';
    wait for 30 ns;
    assert q = '0' and qb = '1' report "RTL step 12: Falling holds" severity failure;
    assert gq = '0' and gqb = '1' report "Gates step 12: Falling holds" severity failure;
    assert q = gq and qb = gqb report "Equivalence step 12" severity failure;
    report "PASS step 12: Falling holds" severity note;
    j <= '1'; k <= '1'; clk <= '1';
    wait for 30 ns;
    assert q = '1' and qb = '0' report "RTL step 13: Toggle to 1" severity failure;
    assert gq = '1' and gqb = '0' report "Gates step 13: Toggle to 1" severity failure;
    assert q = gq and qb = gqb report "Equivalence step 13" severity failure;
    report "PASS step 13: Toggle to 1" severity note;
    j <= '0'; k <= '1'; clk <= '0';
    wait for 30 ns;
    assert q = '1' and qb = '0' report "RTL step 14: Prepare Reset again" severity failure;
    assert gq = '1' and gqb = '0' report "Gates step 14: Prepare Reset again" severity failure;
    assert q = gq and qb = gqb report "Equivalence step 14" severity failure;
    report "PASS step 14: Prepare Reset again" severity note;
    j <= '0'; k <= '1'; clk <= '1';
    wait for 30 ns;
    assert q = '0' and qb = '1' report "RTL step 15: Reset again" severity failure;
    assert gq = '0' and gqb = '1' report "Gates step 15: Reset again" severity failure;
    assert q = gq and qb = gqb report "Equivalence step 15" severity failure;
    report "PASS step 15: Reset again" severity note;
    report "ALL PASS jk_ff" severity note;
    finish;
    wait;
  end process;
end architecture;
