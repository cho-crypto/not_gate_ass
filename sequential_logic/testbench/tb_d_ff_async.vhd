library ieee;
use ieee.std_logic_1164.all;

use std.env.all;

entity tb_d_ff_async is end;
architecture test of tb_d_ff_async is
  signal d, clk, set, clr : std_logic := '0';
  signal q, qb, gq, gqb : std_logic;
begin
  dut: entity work.d_ff_async(rtl) port map(d, clk, set, clr, q, qb);
  net: entity work.d_ff_async_gates(gates) port map(d, clk, set, clr, gq, gqb);
  process
  begin
    d <= '0'; clk <= '0'; set <= '0'; clr <= '1';
    wait for 30 ns;
    assert q = '0' and qb = '1' report "RTL step 1: Async Clear at low" severity failure;
    assert gq = '0' and gqb = '1' report "Gates step 1: Async Clear at low" severity failure;
    assert q = gq and qb = gqb report "Equivalence step 1" severity failure;
    report "PASS step 1: Async Clear at low" severity note;
    d <= '0'; clk <= '0'; set <= '1'; clr <= '1';
    wait for 30 ns;
    assert q = '0' and qb = '1' report "RTL step 2: Clear wins both high" severity failure;
    assert gq = '0' and gqb = '1' report "Gates step 2: Clear wins both high" severity failure;
    assert q = gq and qb = gqb report "Equivalence step 2" severity failure;
    report "PASS step 2: Clear wins both high" severity note;
    d <= '0'; clk <= '0'; set <= '1'; clr <= '0';
    wait for 30 ns;
    assert q = '1' and qb = '0' report "RTL step 3: Async Set no edge" severity failure;
    assert gq = '1' and gqb = '0' report "Gates step 3: Async Set no edge" severity failure;
    assert q = gq and qb = gqb report "Equivalence step 3" severity failure;
    report "PASS step 3: Async Set no edge" severity note;
    d <= '0'; clk <= '0'; set <= '0'; clr <= '0';
    wait for 30 ns;
    assert q = '1' and qb = '0' report "RTL step 4: Release Set holds" severity failure;
    assert gq = '1' and gqb = '0' report "Gates step 4: Release Set holds" severity failure;
    assert q = gq and qb = gqb report "Equivalence step 4" severity failure;
    report "PASS step 4: Release Set holds" severity note;
    d <= '0'; clk <= '1'; set <= '0'; clr <= '0';
    wait for 30 ns;
    assert q = '0' and qb = '1' report "RTL step 5: Normal rising captures 0" severity failure;
    assert gq = '0' and gqb = '1' report "Gates step 5: Normal rising captures 0" severity failure;
    assert q = gq and qb = gqb report "Equivalence step 5" severity failure;
    report "PASS step 5: Normal rising captures 0" severity note;
    d <= '1'; clk <= '1'; set <= '0'; clr <= '0';
    wait for 30 ns;
    assert q = '0' and qb = '1' report "RTL step 6: High D change holds" severity failure;
    assert gq = '0' and gqb = '1' report "Gates step 6: High D change holds" severity failure;
    assert q = gq and qb = gqb report "Equivalence step 6" severity failure;
    report "PASS step 6: High D change holds" severity note;
    d <= '1'; clk <= '1'; set <= '1'; clr <= '0';
    wait for 30 ns;
    assert q = '1' and qb = '0' report "RTL step 7: Async Set while high" severity failure;
    assert gq = '1' and gqb = '0' report "Gates step 7: Async Set while high" severity failure;
    assert q = gq and qb = gqb report "Equivalence step 7" severity failure;
    report "PASS step 7: Async Set while high" severity note;
    d <= '1'; clk <= '1'; set <= '1'; clr <= '1';
    wait for 30 ns;
    assert q = '0' and qb = '1' report "RTL step 8: Async Clear overrides Set" severity failure;
    assert gq = '0' and gqb = '1' report "Gates step 8: Async Clear overrides Set" severity failure;
    assert q = gq and qb = gqb report "Equivalence step 8" severity failure;
    report "PASS step 8: Async Clear overrides Set" severity note;
    d <= '1'; clk <= '1'; set <= '0'; clr <= '1';
    wait for 30 ns;
    assert q = '0' and qb = '1' report "RTL step 9: Clear maintained" severity failure;
    assert gq = '0' and gqb = '1' report "Gates step 9: Clear maintained" severity failure;
    assert q = gq and qb = gqb report "Equivalence step 9" severity failure;
    report "PASS step 9: Clear maintained" severity note;
    d <= '1'; clk <= '1'; set <= '0'; clr <= '0';
    wait for 30 ns;
    assert q = '0' and qb = '1' report "RTL step 10: Release Clear no edge" severity failure;
    assert gq = '0' and gqb = '1' report "Gates step 10: Release Clear no edge" severity failure;
    assert q = gq and qb = gqb report "Equivalence step 10" severity failure;
    report "PASS step 10: Release Clear no edge" severity note;
    d <= '1'; clk <= '0'; set <= '0'; clr <= '0';
    wait for 30 ns;
    assert q = '0' and qb = '1' report "RTL step 11: Falling holds" severity failure;
    assert gq = '0' and gqb = '1' report "Gates step 11: Falling holds" severity failure;
    assert q = gq and qb = gqb report "Equivalence step 11" severity failure;
    report "PASS step 11: Falling holds" severity note;
    d <= '1'; clk <= '1'; set <= '0'; clr <= '0';
    wait for 30 ns;
    assert q = '1' and qb = '0' report "RTL step 12: Normal rising captures 1" severity failure;
    assert gq = '1' and gqb = '0' report "Gates step 12: Normal rising captures 1" severity failure;
    assert q = gq and qb = gqb report "Equivalence step 12" severity failure;
    report "PASS step 12: Normal rising captures 1" severity note;
    d <= '1'; clk <= '0'; set <= '0'; clr <= '0';
    wait for 30 ns;
    assert q = '1' and qb = '0' report "RTL step 13: Return low" severity failure;
    assert gq = '1' and gqb = '0' report "Gates step 13: Return low" severity failure;
    assert q = gq and qb = gqb report "Equivalence step 13" severity failure;
    report "PASS step 13: Return low" severity note;
    report "ALL PASS d_ff_async" severity note;
    finish;
    wait;
  end process;
end architecture;
